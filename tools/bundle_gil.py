"""Assemble one Lua client script for a Miliastra editor mapping."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LOADER = """local factories, loaded, loading = {}, {}, {}
local function require(name)
    if loaded[name] ~= nil then return loaded[name] end
    assert(not loading[name], "circular gameplay module " .. name)
    local factory = assert(factories[name], "missing gameplay module " .. name)
    loading[name] = true
    local result = factory()
    assert(result ~= nil, "gameplay module must return a value: " .. name)
    loaded[name], loading[name] = result, nil
    return result
end
"""


def build():
    modules = sorted(path for directory in ("data", "game") for path in (ROOT / directory).rglob("*.lua"))
    pieces = ["-- Generated by tools/bundle_gil.py\n", LOADER]
    for path in modules:
        name = ".".join(path.relative_to(ROOT).with_suffix("").parts)
        pieces.append(f"factories[{json.dumps(name)}] = function()\n")
        pieces.append(path.read_text(encoding="utf-8"))
        pieces.append("\nend\n")
    pieces.append((ROOT / "gil/client.lua").read_text(encoding="utf-8"))
    return "".join(pieces)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(build(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
